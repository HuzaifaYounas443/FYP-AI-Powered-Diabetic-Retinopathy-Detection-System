"""
Email report service using SMTP (Gmail by default).
Set env vars:  SMTP_USER, SMTP_PASS, SMTP_HOST (opt), SMTP_PORT (opt)
"""
import os
import smtplib
from email.mime.multipart import MIMEMultipart
from email.mime.text import MIMEText
from datetime import datetime

SMTP_HOST = os.environ.get('SMTP_HOST', 'smtp.gmail.com')
SMTP_PORT = int(os.environ.get('SMTP_PORT', 587))
SMTP_USER = os.environ.get('SMTP_USER', '')
SMTP_PASS = os.environ.get('SMTP_PASS', '')

SEVERITY_COLORS = {
    0: '#22c55e', 1: '#84cc16', 2: '#f59e0b', 3: '#f97316', 4: '#ef4444'
}

def send_report_email(to_email: str, patient_name: str, result: dict, scan_id: int):
    if not SMTP_USER or not SMTP_PASS:
        raise RuntimeError(
            "SMTP credentials not configured. Set SMTP_USER and SMTP_PASS environment variables."
        )

    level = result.get('severity_level', 0)
    color = SEVERITY_COLORS.get(level, '#6366f1')
    label = result.get('severity_label', 'Unknown')
    confidence = result.get('confidence', 0)
    recommendations = result.get('recommendations', '')
    date_str = datetime.now().strftime('%B %d, %Y at %I:%M %p')

    html = f"""
<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body {{ font-family: 'Segoe UI', Arial, sans-serif; background: #f0f4f8; margin: 0; padding: 0; }}
    .container {{ max-width: 600px; margin: 30px auto; background: #fff; border-radius: 16px; overflow: hidden; box-shadow: 0 4px 24px rgba(0,0,0,0.08); }}
    .header {{ background: linear-gradient(135deg, #1e3a5f 0%, #0ea5e9 100%); padding: 40px 32px; text-align: center; }}
    .header h1 {{ color: #fff; margin: 0; font-size: 24px; letter-spacing: 1px; }}
    .header p {{ color: rgba(255,255,255,0.8); margin: 8px 0 0; font-size: 13px; }}
    .body {{ padding: 32px; }}
    .result-card {{ background: #f8fafc; border-left: 5px solid {color}; border-radius: 12px; padding: 20px 24px; margin: 24px 0; }}
    .result-label {{ font-size: 22px; font-weight: 700; color: {color}; }}
    .confidence {{ font-size: 13px; color: #64748b; margin-top: 4px; }}
    .section-title {{ font-size: 14px; font-weight: 600; color: #1e3a5f; text-transform: uppercase; letter-spacing: 0.5px; margin: 24px 0 8px; }}
    .rec-box {{ background: #eff6ff; border-radius: 10px; padding: 16px 20px; color: #1e40af; font-size: 14px; line-height: 1.7; }}
    .footer {{ background: #f8fafc; border-top: 1px solid #e2e8f0; padding: 20px 32px; text-align: center; color: #94a3b8; font-size: 12px; }}
    .badge {{ display: inline-block; padding: 4px 12px; border-radius: 20px; font-size: 12px; font-weight: 600; background: {color}22; color: {color}; }}
  </style>
</head>
<body>
  <div class="container">
    <div class="header">
      <h1>👁 RetinAI Detection Report</h1>
      <p>Scan ID: #{scan_id} &nbsp;|&nbsp; {date_str}</p>
    </div>
    <div class="body">
      <p>Dear <strong>{patient_name}</strong>,</p>
      <p>Your retinal scan has been analyzed by our AI-powered diabetic retinopathy detection system. Please review your results below and share them with your healthcare provider.</p>

      <div class="result-card">
        <div class="result-label">{label}</div>
        <div class="confidence">Confidence: {confidence:.1f}% &nbsp; <span class="badge">Ensemble AI</span></div>
      </div>

      <div class="section-title">Clinical Recommendation</div>
      <div class="rec-box">{recommendations}</div>

      <div class="section-title">Important Notice</div>
      <p style="color:#64748b; font-size:13px; line-height:1.7;">
        This report is generated by an AI system and is intended to assist healthcare professionals. 
        It is <strong>not a substitute</strong> for professional medical advice, diagnosis, or treatment. 
        Please consult your ophthalmologist or endocrinologist for proper evaluation.
      </p>
    </div>
    <div class="footer">
      &copy; {datetime.now().year} RetinAI Detection System &nbsp;&bull;&nbsp; University of Haripur, Department of IT<br>
      This email was sent automatically. Please do not reply.
    </div>
  </div>
</body>
</html>
"""

    msg = MIMEMultipart('alternative')
    msg['Subject'] = f'Your Retinal Scan Report – Scan #{scan_id}'
    msg['From'] = f'RetinAI System <{SMTP_USER}>'
    msg['To'] = to_email
    msg.attach(MIMEText(html, 'html'))

    with smtplib.SMTP(SMTP_HOST, SMTP_PORT) as server:
        server.starttls()
        server.login(SMTP_USER, SMTP_PASS)
        server.sendmail(SMTP_USER, to_email, msg.as_string())
